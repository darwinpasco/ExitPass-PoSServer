\set ON_ERROR_STOP on

BEGIN;

REVOKE ALL ON SCHEMA pos FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA pos TO posserver_admin;
GRANT USAGE ON SCHEMA pos TO posserver_app, posserver_backup;

REVOKE ALL ON ALL TABLES IN SCHEMA pos FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA pos FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA pos FROM PUBLIC;

GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA pos TO posserver_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA pos TO posserver_app;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA pos TO posserver_app;

GRANT SELECT ON ALL TABLES IN SCHEMA pos TO posserver_backup;
GRANT SELECT ON ALL SEQUENCES IN SCHEMA pos TO posserver_backup;

ALTER DEFAULT PRIVILEGES FOR ROLE posserver_admin IN SCHEMA pos
    REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE posserver_admin IN SCHEMA pos
    REVOKE ALL ON SEQUENCES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE posserver_admin IN SCHEMA pos
    REVOKE ALL ON FUNCTIONS FROM PUBLIC;

ALTER DEFAULT PRIVILEGES FOR ROLE posserver_admin IN SCHEMA pos
    GRANT SELECT, INSERT, UPDATE ON TABLES TO posserver_app;
ALTER DEFAULT PRIVILEGES FOR ROLE posserver_admin IN SCHEMA pos
    GRANT USAGE, SELECT ON SEQUENCES TO posserver_app;
ALTER DEFAULT PRIVILEGES FOR ROLE posserver_admin IN SCHEMA pos
    GRANT EXECUTE ON FUNCTIONS TO posserver_app;
ALTER DEFAULT PRIVILEGES FOR ROLE posserver_admin IN SCHEMA pos
    GRANT SELECT ON TABLES TO posserver_backup;
ALTER DEFAULT PRIVILEGES FOR ROLE posserver_admin IN SCHEMA pos
    GRANT SELECT ON SEQUENCES TO posserver_backup;

COMMIT;
